drop database FoodDeliveryDB;

--  1. Customers Table --

CREATE TABLE Customers (
    CustomerID INT PRIMARY KEY,
    CustomerName VARCHAR(100),
    Phone VARCHAR(15),
    City VARCHAR(50)
);

--  2. Restaurants table --

CREATE TABLE Restaurants (
    RestaurantID INT PRIMARY KEY,
    RestaurantName VARCHAR(100),
    City VARCHAR(50),
    Category VARCHAR(50),
    Rating DECIMAL(2,1)
);

--  3.FoodItems table --

CREATE TABLE FoodItems (
    FoodID INT PRIMARY KEY,
    RestaurantID INT,
    FoodName VARCHAR(100),
    Price DECIMAL(10,2),
    FOREIGN KEY (RestaurantID) REFERENCES Restaurants(RestaurantID)
);

--  4.DeliveryPartners Table  --

CREATE TABLE DeliveryPartners (
    DeliveryPartnerID INT PRIMARY KEY,
    PartnerName VARCHAR(100),
    Phone VARCHAR(15),
    City VARCHAR(50)
);

--  5.Orders Table --

CREATE TABLE Orders (
    OrderID INT PRIMARY KEY,
    CustomerID INT,
    RestaurantID INT,
    DeliveryPartnerID INT,
    OrderDate DATE,
    OrderStatus VARCHAR(30),
    TotalAmount DECIMAL(10,2),

    FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID),
    FOREIGN KEY (RestaurantID) REFERENCES Restaurants(RestaurantID),
    FOREIGN KEY (DeliveryPartnerID) REFERENCES DeliveryPartners(DeliveryPartnerID)
);

--  6.OrderDetails Table --

CREATE TABLE OrderDetails (
    OrderDetailID INT PRIMARY KEY,
    OrderID INT,
    FoodID INT,
    Quantity INT,
    Price DECIMAL(10,2),

    FOREIGN KEY (OrderID) REFERENCES Orders(OrderID),
    FOREIGN KEY (FoodID) REFERENCES FoodItems(FoodID)
);

